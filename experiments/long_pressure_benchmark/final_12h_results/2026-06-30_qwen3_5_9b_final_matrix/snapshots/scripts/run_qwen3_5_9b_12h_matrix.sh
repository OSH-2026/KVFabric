json_value() {
  local config_path="$1"
  local path="$2"
  local default="$3"
  python3 - "$config_path" "$path" "$default" <<'PY'
import json
import sys
from pathlib import Path

config = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
value = config
for part in sys.argv[2].split("."):
    if isinstance(value, dict) and part in value:
        value = value[part]
    else:
        value = sys.argv[3]
        break
print(value)
PY
}

segment_sum_seconds() {
  local config_path="$1"
  python3 - "$config_path" <<'PY'
import json
import sys
from pathlib import Path

config = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
segments = config.get("loadgen", {}).get("segments") or []
print(int(sum(float(segment.get("duration_seconds", 0)) for segment in segments)))
PY
}

capacity_value() {
  case "$1" in
    small) printf '0.55\n' ;;
    medium) printf '0.70\n' ;;
    large) printf '0.85\n' ;;
    *)
      echo "Unknown KV capacity profile: $1" >&2
      return 1
      ;;
  esac
}

apply_capacity() {
