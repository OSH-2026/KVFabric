#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)
# shellcheck disable=SC1091
source "$SCRIPT_DIR/common.sh"

REMOTE_HOST="${REMOTE_HOST:-robowalker}"
REMOTE_SSH_TARGET="${REMOTE_SSH_TARGET:-$REMOTE_HOST}"
REMOTE_SSH_OPTS="${REMOTE_SSH_OPTS:-}"
REMOTE_PROJECT="${REMOTE_PROJECT:-/home/zhoujiarun/KVFabric}"
REMOTE_VENV="${REMOTE_VENV:-.venv_kvfabric_0221}"
REMOTE_PRESET="${REMOTE_PRESET:-qwen3_5_27b}"
REMOTE_CONFIG="${REMOTE_CONFIG:-experiments/long_pressure_benchmark/configs/qwen3_5_27b_enterprise_mixed_trace_12h.json}"
REMOTE_JOB_NAME="${REMOTE_JOB_NAME:-remote_27b_enterprise_mixed_trace_12h}"

KVFABRIC_AB_POLICIES="${KVFABRIC_AB_POLICIES:-lru shared_aware family_protect}"
TRACE_BENCH_HINT_REGIME="${TRACE_BENCH_HINT_REGIME:-partial_hints}"
TRACE_BENCH_MAX_MODEL_LEN="${TRACE_BENCH_MAX_MODEL_LEN:-4096}"
TRACE_BENCH_MAX_NUM_SEQS="${TRACE_BENCH_MAX_NUM_SEQS:-10}"
TRACE_BENCH_MAX_NUM_BATCHED_TOKENS="${TRACE_BENCH_MAX_NUM_BATCHED_TOKENS:-8192}"
TRACE_BENCH_MAX_IN_FLIGHT="${TRACE_BENCH_MAX_IN_FLIGHT:-32}"
TRACE_BENCH_WARMUP_SECONDS="${TRACE_BENCH_WARMUP_SECONDS:-300}"
TRACE_BENCH_TIMEOUT_SECONDS="${TRACE_BENCH_TIMEOUT_SECONDS:-900}"
TRACE_BENCH_METRICS_INTERVAL="${TRACE_BENCH_METRICS_INTERVAL:-30}"
TRACE_BENCH_RAW_SAMPLE_RATE="${TRACE_BENCH_RAW_SAMPLE_RATE:-0.02}"
TRACE_BENCH_RAW_SAMPLE_LIMIT="${TRACE_BENCH_RAW_SAMPLE_LIMIT:-2000}"

load_common_env

ssh $REMOTE_SSH_OPTS "$REMOTE_SSH_TARGET" "bash -s" <<REMOTE
set -euo pipefail
cd "$REMOTE_PROJECT"
mkdir -p vllm_baseline/runtime_kvfabric_0221/jobs
bash vllm_baseline/scripts/stop_server.sh "$REMOTE_PRESET" || true

cat > "vllm_baseline/runtime_kvfabric_0221/jobs/${REMOTE_JOB_NAME}.sh" <<'RUN'
#!/usr/bin/env bash
set -euo pipefail
cd "\${REMOTE_PROJECT:-/home/zhoujiarun/KVFabric}"

export VLLM_VENV_DIR="\${REMOTE_VENV:-.venv_kvfabric_0221}"
export VLLM_SERVER_START_TIMEOUT="\${VLLM_SERVER_START_TIMEOUT:-900}"
export KVFABRIC_AB_POLICIES="\${KVFABRIC_AB_POLICIES:-lru shared_aware family_protect}"
export TRACE_BENCH_HINT_REGIME="\${TRACE_BENCH_HINT_REGIME:-partial_hints}"
export TRACE_BENCH_MAX_MODEL_LEN="\${TRACE_BENCH_MAX_MODEL_LEN:-4096}"
export TRACE_BENCH_MAX_NUM_SEQS="\${TRACE_BENCH_MAX_NUM_SEQS:-10}"
export TRACE_BENCH_MAX_NUM_BATCHED_TOKENS="\${TRACE_BENCH_MAX_NUM_BATCHED_TOKENS:-8192}"
export TRACE_BENCH_MAX_IN_FLIGHT="\${TRACE_BENCH_MAX_IN_FLIGHT:-32}"
export TRACE_BENCH_WARMUP_SECONDS="\${TRACE_BENCH_WARMUP_SECONDS:-300}"
export TRACE_BENCH_TIMEOUT_SECONDS="\${TRACE_BENCH_TIMEOUT_SECONDS:-900}"
export TRACE_BENCH_METRICS_INTERVAL="\${TRACE_BENCH_METRICS_INTERVAL:-30}"
export TRACE_BENCH_RAW_SAMPLE_RATE="\${TRACE_BENCH_RAW_SAMPLE_RATE:-0.02}"
export TRACE_BENCH_RAW_SAMPLE_LIMIT="\${TRACE_BENCH_RAW_SAMPLE_LIMIT:-2000}"
export KV_CACHE_METRICS="\${KV_CACHE_METRICS:-1}"
export KV_CACHE_METRICS_SAMPLE="\${KV_CACHE_METRICS_SAMPLE:-0.05}"
export KVFABRIC_LOG_BUFFER_SIZE="\${KVFABRIC_LOG_BUFFER_SIZE:-8192}"
export KVFABRIC_RANK_LOG_CANDIDATES="\${KVFABRIC_RANK_LOG_CANDIDATES:-0}"

bash experiments/long_pressure_benchmark/scripts/run_remote_27b_trace_long_benchmark.sh \
  "\${REMOTE_PRESET:-qwen3_5_27b}" \
  "\${REMOTE_CONFIG:-experiments/long_pressure_benchmark/configs/qwen3_5_27b_enterprise_mixed_trace_12h.json}"
RUN

chmod +x "vllm_baseline/runtime_kvfabric_0221/jobs/${REMOTE_JOB_NAME}.sh"
REMOTE_PROJECT="$REMOTE_PROJECT" \
REMOTE_VENV="$REMOTE_VENV" \
REMOTE_PRESET="$REMOTE_PRESET" \
REMOTE_CONFIG="$REMOTE_CONFIG" \
KVFABRIC_AB_POLICIES="$KVFABRIC_AB_POLICIES" \
TRACE_BENCH_HINT_REGIME="$TRACE_BENCH_HINT_REGIME" \
TRACE_BENCH_MAX_MODEL_LEN="$TRACE_BENCH_MAX_MODEL_LEN" \
TRACE_BENCH_MAX_NUM_SEQS="$TRACE_BENCH_MAX_NUM_SEQS" \
TRACE_BENCH_MAX_NUM_BATCHED_TOKENS="$TRACE_BENCH_MAX_NUM_BATCHED_TOKENS" \
TRACE_BENCH_MAX_IN_FLIGHT="$TRACE_BENCH_MAX_IN_FLIGHT" \
TRACE_BENCH_WARMUP_SECONDS="$TRACE_BENCH_WARMUP_SECONDS" \
TRACE_BENCH_TIMEOUT_SECONDS="$TRACE_BENCH_TIMEOUT_SECONDS" \
TRACE_BENCH_METRICS_INTERVAL="$TRACE_BENCH_METRICS_INTERVAL" \
TRACE_BENCH_RAW_SAMPLE_RATE="$TRACE_BENCH_RAW_SAMPLE_RATE" \
TRACE_BENCH_RAW_SAMPLE_LIMIT="$TRACE_BENCH_RAW_SAMPLE_LIMIT" \
nohup bash "vllm_baseline/runtime_kvfabric_0221/jobs/${REMOTE_JOB_NAME}.sh" \
  > "vllm_baseline/runtime_kvfabric_0221/jobs/${REMOTE_JOB_NAME}.log" 2>&1 &
echo \$! > "vllm_baseline/runtime_kvfabric_0221/jobs/${REMOTE_JOB_NAME}.pid"
echo "started_${REMOTE_JOB_NAME}_pid=\$(cat vllm_baseline/runtime_kvfabric_0221/jobs/${REMOTE_JOB_NAME}.pid)"
echo "job_log=$REMOTE_PROJECT/vllm_baseline/runtime_kvfabric_0221/jobs/${REMOTE_JOB_NAME}.log"
REMOTE
