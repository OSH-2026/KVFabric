#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "$0")" && pwd)

export REMOTE_JOB_NAME="${REMOTE_JOB_NAME:-remote_27b_hint_pressure_10h}"
export REMOTE_CONFIG="${REMOTE_CONFIG:-experiments/prebenchmark_validation/configs/qwen3_5_27b_hint_pressure_10h.json}"

# Three policies x 12,000 seconds each gives an approximately 10 hour run.
export LONG_BENCH_DURATION_SECONDS="${LONG_BENCH_DURATION_SECONDS:-12000}"
export LONG_BENCH_WARMUP_SECONDS="${LONG_BENCH_WARMUP_SECONDS:-180}"
export LONG_BENCH_CONCURRENCY="${LONG_BENCH_CONCURRENCY:-10}"
export LONG_BENCH_MAX_MODEL_LEN="${LONG_BENCH_MAX_MODEL_LEN:-4096}"
export LONG_BENCH_MAX_NUM_SEQS="${LONG_BENCH_MAX_NUM_SEQS:-10}"
export LONG_BENCH_MAX_NUM_BATCHED_TOKENS="${LONG_BENCH_MAX_NUM_BATCHED_TOKENS:-16384}"
export LONG_BENCH_TIMEOUT_SECONDS="${LONG_BENCH_TIMEOUT_SECONDS:-600}"
export LONG_BENCH_RAW_SAMPLE_RATE="${LONG_BENCH_RAW_SAMPLE_RATE:-0.02}"
export LONG_BENCH_RAW_SAMPLE_LIMIT="${LONG_BENCH_RAW_SAMPLE_LIMIT:-2000}"

# The hint-aware benchmark relies on explicit no-reuse requests bypassing
# prefix-cache insertion under pressure. Transient and durable families still
# keep discovery anchors.
export KVFABRIC_HINT_LOW_REUSE_DISCOVERY_TOKENS="${KVFABRIC_HINT_LOW_REUSE_DISCOVERY_TOKENS:-0}"
export KVFABRIC_HINT_LOW_REUSE_MIN_CACHE_BLOCKS="${KVFABRIC_HINT_LOW_REUSE_MIN_CACHE_BLOCKS:-0}"
export KVFABRIC_HINT_BYPASS_DISCOVERY_TOKENS="${KVFABRIC_HINT_BYPASS_DISCOVERY_TOKENS:-0}"
export KVFABRIC_HINT_BYPASS_MIN_CACHE_BLOCKS="${KVFABRIC_HINT_BYPASS_MIN_CACHE_BLOCKS:-0}"
export KVFABRIC_HINT_TRANSIENT_DISCOVERY_TOKENS="${KVFABRIC_HINT_TRANSIENT_DISCOVERY_TOKENS:-1568}"
export KVFABRIC_HINT_DURABLE_DISCOVERY_TOKENS="${KVFABRIC_HINT_DURABLE_DISCOVERY_TOKENS:-2352}"
export KVFABRIC_ADMISSION_COLD_DISCOVERY_TOKENS="${KVFABRIC_ADMISSION_COLD_DISCOVERY_TOKENS:-1568}"
export KVFABRIC_ADMISSION_REUSE_MIN_HIT_TOKENS="${KVFABRIC_ADMISSION_REUSE_MIN_HIT_TOKENS:-784}"
export KVFABRIC_SCHEDULER_DEFER_MIN_RISK_RATIO="${KVFABRIC_SCHEDULER_DEFER_MIN_RISK_RATIO:-0.50}"

bash "$SCRIPT_DIR/run_remote_27b_realistic_10h_benchmark.sh"
